"""Tiny i18n dictionary. English only for now; Turkish strings arrive in Phase 5."""

from __future__ import annotations

STRINGS: dict[str, dict[str, str]] = {
    "en": {
        "title": "PR Brief",
        "changes": "What changed",
        "commit": "Suggested commit message",
        "risks": "Risks",
        "no_risks": "No notable risks identified.",
        "checklist": "Review checklist",
        "missing_tests": "Missing tests",
        "run_details": "Run details",
        "files": "Files analyzed: {analyzed} · skipped: {skipped}",
        "omitted": "Not analyzed (too large for the input budget): {paths}",
        "truncated": "Truncated to fit the input budget: {paths}",
        "redactions": "Secrets/PII masked before sending: {count}",
        "chunks": "Chunks: {chunks}",
        "cached": "Served from cache: no model call was made.",
        "model": "Provider: {provider} · model: `{model}`",
        "tokens": "Tokens: input {input} · output {output}",
        "footer": "Generated by [pr-brief]({url}) · Configure or disable it: {url}#configuration",
        "failure": "Could not generate a brief for this PR.",
        "no_reviewable": "Nothing to review: no reviewable files remain after filtering.",
    },
}


def t(language: str, key: str, **kwargs: object) -> str:
    table = STRINGS.get(language, STRINGS["en"])
    template = table.get(key) or STRINGS["en"][key]
    return template.format(**kwargs) if kwargs else template
